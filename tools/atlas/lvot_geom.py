def map_path(d, fx):
    """Переводит путь из координат атласа в другую систему (только абсолютные команды M L C Q Z)."""
    import re
    toks = re.findall(r"[MLCQZlZ]|-?\d+(?:\.\d+)?", d)
    out, nums, rel = [], [], False
    for t in toks:
        if t.isalpha():
            if nums:
                out.append(" ".join(nums)); nums = []
            out.append(t); rel = t.islower()
        else:
            nums.append(t)
            if len(nums) == 2:
                x, y = float(nums[0]), float(nums[1])
                if rel:
                    k = fx(1, 1)[0] - fx(0, 0)[0]
                    out.append(f"{x * k:.1f},{y * k:.1f}")
                else:
                    X, Y = fx(x, y); out.append(f"{X:.1f},{Y:.1f}")
                nums = []
    return " ".join(out)


